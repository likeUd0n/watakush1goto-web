/**
 * 自傷・自殺を示す入力の判定(キーワード)。Android 版 domain/Crisis.kt と同じ一覧。
 * 該当する入力では相談窓口のシートを出し、外部AIに渡す文からは外す。
 *
 * 見逃しを減らすことを優先し、比喩(「死にたいくらい恥ずかしい」)も拾う(安全側に倒す)。
 * 一覧は仮のもの。語の範囲は医療専門家の意見を踏まえて見直す予定。
 */
const TA = 'た[いかく]' // 「〜たい」の活用(たい / たか(った)/ たく(て・なる))

const PATTERNS: RegExp[] = [
  new RegExp(`[死し]に${TA}|死のう|死んじゃい${TA}|死にそう|死んでしまい${TA}|死んだほうが|死んだ方が|死んでしまおう|死んでやる`),
  /自殺|自死|自傷|リスカ|リストカット|オーバードーズ|過剰摂取|OD(?![A-Za-z])/,
  new RegExp(
    `消え${TA}|消えてしまい${TA}|消えてなくなり${TA}|いなくなり${TA}|生きていたくな[いかく]|生きるのが(?:つらい|辛い|しんどい)|生きていても仕方|生きて(?:い)?る意味が(?:ない|無い|わからない|分からない)|生きる意味が(?:ない|無い)`,
  ),
  new RegExp(`首を?吊|飛び降り|飛び込み(?:${TA}|自殺)|手首を切`),
  new RegExp(`楽になりたい.*(?:死|終わ)|(?:終わらせ|終わりにし)たい.*(?:人生|命)|終わりにし${TA}|命を絶`),
  /殺してほしい|殺してくれ/,
]

export function looksLikeCrisis(text: string): boolean {
  // 全角・半角やスペースの揺れで見逃さないよう、空白を除いて正規化する
  const t = text.normalize('NFKC').replace(/\s+/g, '')
  return PATTERNS.some((p) => p.test(t))
}
